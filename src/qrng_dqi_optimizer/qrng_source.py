"""
Silicon-28 QRNG Entropy Source Interface Module
Path: src/qrng_dqi_optimizer/qrng_source.py

Fetches genuine physical quantum random entropy generated by the Si28-Phonon QRNG engine
(or reads verified_si28_bits.npy) and provides cryptographically sound seeds to the
DQI Phase Interferometer Adapter with strict Coupon Collector entropy validation.
"""

import os
import sys
import math
import hashlib
import numpy as np
from typing import Tuple, Dict, Any


class QRNGEntropySource:
    """
    Si-28 포논 양자 엔트로피 수급기 및 쿠폰 수집가(Coupon Collector) 신뢰성 검증 모듈
    """

    def __init__(self, seed_path: str = "data/verified_si28_bits.npy"):
        """
        :param seed_path: Si28-Phonon QRNG에서 생성된 verified_si28_bits.npy 시드 파일 경로
        """
        self.seed_path = seed_path

    def _trigger_seed_generation(self) -> bool:
        """
        generate_seed.py 모듈을 동적으로 호출하여 진성 양자 시드 파일(.npy) 생성을 시도
        """
        try:
            # 현재 작업 디렉토리 경로 등록 (외부 저장소 연동 지원)
            sys.path.append(os.getcwd())
            from generate_seed import generate_and_save_si28_seed
            generate_and_save_si28_seed(bit_length=1000000, num_runs=1)
            return True
        except Exception:
            return False

    def get_entropy_seed(self, num_bytes: int = 256) -> Tuple[bytes, Dict[str, Any]]:
        """
        진성 양자 엔트로피 시드 바이트 및 신뢰 검증 메타데이터 반환

        :param num_bytes: 인출할 엔트로피 바이트 수 (기본 256바이트 = 2,048비트)
        :return: (raw_bytes, stats_dict)
        """
        raw_bytes = None
        source_type = "Unknown"

        # 1. seed_path에 파일이 없으면 generate_seed.py 가동 시도
        if not os.path.exists(self.seed_path):
            self._trigger_seed_generation()

        # 2. Si28 진성 양자 시드 파일(.npy) 로드 및 packbits 변환
        if os.path.exists(self.seed_path):
            try:
                bit_array = np.load(self.seed_path)
                
                # N-차원 배열 정형화 (1차원 평탄화)
                if bit_array.ndim > 1:
                    bit_array = bit_array.flatten()

                # 요구되는 바이트 수에 맞춰 비트 슬라이싱 및 바이트 패킹
                req_bits = num_bytes * 8
                if len(bit_array) < req_bits:
                    # 비트 수가 부족할 경우 순환 패딩(wrap)으로 최소 바이트 보장
                    bit_array = np.pad(bit_array, (0, req_bits - len(bit_array)), mode='wrap')
                
                selected_bits = bit_array[:req_bits]
                raw_bytes = np.packbits(selected_bits).tobytes()
                source_type = "Si28_Phonon_Quantum_QPU"
            except Exception as e:
                # 파일 읽기 실패 시 물리 엔트로피 폴백 작동
                raw_bytes = os.urandom(num_bytes)
                source_type = f"OS_Physical_Entropy_Fallback (Error: {str(e)})"
        else:
            # 3. 시드 파일 미발견 시 OS 물리 무작위 엔트로피 폴백
            raw_bytes = os.urandom(num_bytes)
            source_type = "OS_Physical_Entropy_Fallback"

        # 4. 쿠폰 수집가 (Coupon Collector) 고유 바이트 집계율 산출 (N=256 기준)
        unique_bytes_count = len(set(raw_bytes))
        max_possible_unique = min(256, len(raw_bytes))
        coupon_score = unique_bytes_count / float(max_possible_unique)

        # 5. SHA-256 암호학적 핑거프린트 생성
        sha256_hash = hashlib.sha256(raw_bytes).hexdigest()

        # 6. 신뢰성 검증 통계 리포트 작성
        stats = {
            "source_type": source_type,
            "seed_bytes_len": len(raw_bytes),
            "unique_bytes_count": unique_bytes_count,
            "coupon_score": coupon_score,
            "is_valid": coupon_score >= 0.50,  # 50% 이상 고유 바이트 확보 필수 검증
            "sha256_fingerprint": sha256_hash,
            "seed_path_used": self.seed_path if "Si28" in source_type else "N/A"
        }

        return raw_bytes, stats


